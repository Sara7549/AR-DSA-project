using UnityEngine;
using UnityEngine.UI;
using TMPro;
using System.Collections;

public class QueueUIManager : MonoBehaviour
{
    [Header("UI Elements")]
    public TextMeshProUGUI instructionText;
    public GameObject winPanel;
    public TextMeshProUGUI winText;
    public Button quizButton;

    [Header("Move Counter")]
    // Assign a ALWAYS-VISIBLE TextMeshPro on your HUD (not inside the win panel)
    public TextMeshProUGUI moveCountText;

    [Header("Instructions Panel")]
    public GameObject instructionsPanel;   // the full open panel
    public GameObject instructionIcon;     // the small icon shown when minimised
    public Button restartButton;
    public Button backButton;

    // Cached so ShowInstructions() can snap back to the right place
    private Vector3 originalScale;
    private Vector3 originalPosition;
    private bool instructionMinimized = false;

    private bool isPlaced = false;
    private bool firstMoveMade = false;
    private Coroutine feedbackCoroutine;

    private void Start()
    {
        if (instructionText != null)
            instructionText.text = "";

        if (winPanel != null)
            winPanel.SetActive(false);

        // Instructions panel starts OPEN; icon starts hidden
        if (instructionsPanel != null)
        {
            instructionsPanel.SetActive(false);
            RectTransform r =
                instructionsPanel.GetComponent<RectTransform>();
            originalScale = r.localScale;
            originalPosition = r.anchoredPosition;
        }

        if (instructionIcon != null)
            instructionIcon.SetActive(true);

        // Initialise move counter display
        UpdateMoveCount(0);

        Invoke("ShowInitialInstruction", 2f);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Instruction text helpers (AR placement states)
    // ?????????????????????????????????????????????????????????????????????????

    private void ShowInitialInstruction()
    {
        if (!isPlaced && instructionText != null)
            instructionText.text =
                "Move your phone slowly to detect a surface";
    }

    public void SetStateScan()
    {
        if (!isPlaced && instructionText != null)
            instructionText.text =
                "Move your phone slowly to detect a surface";
    }

    public void SetStatePlace()
    {
        if (!isPlaced && instructionText != null)
            instructionText.text = "Tap to place the parking lot";
    }

    public void SetStateDrag()
    {
        if (instructionText != null)
        {
            instructionText.color = Color.white;
            instructionText.text = "Drag a vehicle to move it";
        }
    }

    public void OnGamePlaced(GameObject queueGroup)
    {
        isPlaced = true;

        if (instructionText != null)
            instructionText.text =
                "Get the target cars to the exit zone!";
        ShowInstructions();

        Invoke("SetStateDrag", 3f);

        StartCoroutine(PlacementAnimation(queueGroup));
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Move counter  — always visible on the HUD
    // ?????????????????????????????????????????????????????????????????????????

    public void UpdateMoveCount(int moves)
    {
        if (moveCountText != null)
            moveCountText.text = "Moves: " + moves;

        // Minimise the instructions panel after the very first move
        if (moves == 1 && !firstMoveMade)
        {
            firstMoveMade = true;
            MinimizeInstructions();
        }
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Win screen
    // ?????????????????????????????????????????????????????????????????????????

    public void ShowWinScreen(int moves)
    {
        if (winPanel == null) return;
        winPanel.SetActive(true);

        if (winText != null)
            winText.text = "You did it in " + moves + " moves!\n\n" +
                           GetPerformanceMessage(moves);


        if (quizButton != null)
            {
                quizButton.onClick.RemoveAllListeners();

                quizButton.onClick.AddListener(() =>
                {
                    Debug.Log("QUIZ BUTTON CLICKED");

                    winPanel.SetActive(false);

                    QuizUIController quizUI =
                        FindObjectOfType<QuizUIController>();

                    if (quizUI != null)
                        quizUI.StartQuiz("Queue");
                });
            }
           
       }

    private string GetPerformanceMessage(int moves)
    {
        if (moves <= 5) return "Outstanding!";
        if (moves <= 10) return "Great job!";
        if (moves <= 15) return "Well done!";
        return "Keep practicing!";
    }

    public void HideWinPanel()
    {
        if (winPanel != null)
            winPanel.SetActive(false);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Feedback message (temporary, overlays instruction text)
    // ?????????????????????????????????????????????????????????????????????????

    public void ShowFeedback(string message)
    {
        ShowFeedback(message, Color.red);
    }

    public void ShowFeedback(string message, Color color)
    {
        StartCoroutine(ShowFeedbackCoroutine(message, color));
    }

    private IEnumerator ShowFeedbackCoroutine(string message, Color color)
    {
        if (instructionText == null)
            yield break;

        instructionText.text = message;
        instructionText.color = color;

        yield return new WaitForSeconds(2f);

        // Restore NORMAL gameplay instruction
        instructionText.text = "Drag a vehicle to move it";
        instructionText.color = Color.white;

        feedbackCoroutine = null;
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Queue-rule hint helpers (called from QueueController)
    // ?????????????????????????????????????????????????????????????????????????

    public void ShowEnqueueRule()
    {
        ShowFeedback("Queues only accept cars at the back!", Color.cyan);
    }

    public void ShowDequeueRule()
    {
        ShowFeedback("Queues only release cars from the front!", Color.cyan);
    }

    public void ShowHoldingRule()
    {
        ShowFeedback("Holding area: park cars temporarily", Color.cyan);
    }

    public void ShowExitRule()
    {
        ShowFeedback("Target car must be at the front to exit!", Color.red);
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Instructions panel — minimize / show / toggle
    // (same pattern as your other two games)
    // ?????????????????????????????????????????????????????????????????????????

    public void MinimizeInstructions()
    {
        if (instructionsPanel == null) return;
        if (instructionMinimized) return; // already minimised
        StartCoroutine(AnimateInstructionMinimize());
        instructionMinimized = true;
    }

    private IEnumerator AnimateInstructionMinimize()
    {
        RectTransform panelRect =
            instructionsPanel.GetComponent<RectTransform>();
        RectTransform iconRect =
            instructionIcon.GetComponent<RectTransform>();

        float duration = 0.35f;
        float elapsed = 0f;

        Vector3 startScale = panelRect.localScale;
        Vector3 startPos = panelRect.anchoredPosition;
        Vector3 endScale = new Vector3(0.2f, 0.2f, 0.2f);
        Vector3 endPos = iconRect.anchoredPosition;

        while (elapsed < duration)
        {
            elapsed += Time.deltaTime;
            float smoothT = Mathf.SmoothStep(0f, 1f, elapsed / duration);
            panelRect.localScale = Vector3.Lerp(startScale, endScale, smoothT);
            panelRect.anchoredPosition = Vector3.Lerp(startPos, endPos, smoothT);
            yield return null;
        }

        // Snap to final values
        panelRect.localScale = endScale;
        panelRect.anchoredPosition = endPos;

        instructionsPanel.SetActive(false);
        instructionIcon.SetActive(true);
    }

    public void ShowInstructions()
    {
        if (instructionsPanel == null) return;

        RectTransform rect = instructionsPanel.GetComponent<RectTransform>();
        rect.localScale = originalScale;
        rect.anchoredPosition = originalPosition;

        instructionsPanel.SetActive(true);
        // Icon stays visible so the user can tap it again to close
        instructionMinimized = false;
    }

    public void ToggleInstructions()
    {
        if (instructionsPanel == null) return;

        if (instructionsPanel.activeSelf)
            MinimizeInstructions();
        else
            ShowInstructions();
    }

    // ?????????????????????????????????????????????????????????????????????????
    // Placement animation helper
    // ?????????????????????????????????????????????????????????????????????????

    private IEnumerator PlacementAnimation(GameObject obj)
    {
        if (obj == null) yield break;

        Vector3 targetScale = obj.transform.localScale;
        if (targetScale == Vector3.zero)
            targetScale = Vector3.one;

        obj.transform.localScale = Vector3.zero;
        float duration = 0.5f;
        float elapsed = 0f;

        while (elapsed < duration)
        {
            elapsed += Time.deltaTime;
            float t = elapsed / duration;
            t = t * t * (3f - 2f * t); // smoothstep
            obj.transform.localScale =
                Vector3.Lerp(Vector3.zero, targetScale, t);
            yield return null;
        }

        obj.transform.localScale = targetScale;
    }
    
    public void ShowExitPrompt()
    {
        if (instructionText == null) return;

        StopAllCoroutines(); // prevent overwrite
        instructionText.text =
            "All target cars are ready! Move them to the exit zone";
        instructionText.color = Color.cyan;
    }
}